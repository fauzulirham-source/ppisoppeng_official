-- =========================================================================
-- SKRIP DATABASE SUPABASE - PPI KABUPATEN SOPPENG (OFFICIAL)
-- Salin dan jalankan skrip ini di: Supabase Dashboard -> SQL Editor -> New Query -> Run
-- =========================================================================

-- 1. TABEL KEGIATAN (Pengabdian, Kaderisasi, Upacara, Diklat, dll)
CREATE TABLE IF NOT EXISTS public.kegiatan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kategori TEXT NOT NULL,
  judul TEXT NOT NULL,
  tanggal TEXT NOT NULL,
  lokasi TEXT NOT NULL,
  status TEXT DEFAULT 'Terlaksana',
  ringkasan TEXT NOT NULL,
  detail TEXT DEFAULT '',
  foto TEXT DEFAULT '',
  foto_placeholder TEXT DEFAULT 'kegiatan-diklat-paskibra.jpg',
  tags TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL PESAN KONTAK (Aspirasi & Pesan Pengunjung)
CREATE TABLE IF NOT EXISTS public.pesan_kontak (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  email TEXT DEFAULT '',
  whatsapp TEXT DEFAULT '',
  subjek TEXT DEFAULT 'Informasi Umum',
  pesan TEXT NOT NULL,
  status TEXT DEFAULT 'Belum Dibaca',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL ANGGOTA TAMBAHAN (Database Kustom Anggota Admin)
CREATE TABLE IF NOT EXISTS public.anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  angkatan TEXT NOT NULL,
  nra TEXT DEFAULT '',
  tempat_lahir TEXT DEFAULT '',
  sekolah TEXT DEFAULT '',
  alamat TEXT DEFAULT '',
  tingkat TEXT DEFAULT 'Kabupaten',
  no_hp TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- ATUR KEAMANAN ROW LEVEL SECURITY (RLS) & HAK AKSES PUBLIK / ADMIN
-- =========================================================================

-- RLS Kegiatan
ALTER TABLE public.kegiatan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Akses Publik Baca Kegiatan" ON public.kegiatan;
CREATE POLICY "Akses Publik Baca Kegiatan" ON public.kegiatan
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Akses Admin Tambah Kegiatan" ON public.kegiatan;
CREATE POLICY "Akses Admin Tambah Kegiatan" ON public.kegiatan
  FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Akses Admin Ubah Kegiatan" ON public.kegiatan;
CREATE POLICY "Akses Admin Ubah Kegiatan" ON public.kegiatan
  FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Akses Admin Hapus Kegiatan" ON public.kegiatan;
CREATE POLICY "Akses Admin Hapus Kegiatan" ON public.kegiatan
  FOR DELETE USING (true);

-- RLS Pesan Kontak
ALTER TABLE public.pesan_kontak ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Akses Publik Kirim Pesan" ON public.pesan_kontak;
CREATE POLICY "Akses Publik Kirim Pesan" ON public.pesan_kontak
  FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Akses Admin Baca Pesan" ON public.pesan_kontak;
CREATE POLICY "Akses Admin Baca Pesan" ON public.pesan_kontak
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Akses Admin Update Status Pesan" ON public.pesan_kontak;
CREATE POLICY "Akses Admin Update Status Pesan" ON public.pesan_kontak
  FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Akses Admin Hapus Pesan" ON public.pesan_kontak;
CREATE POLICY "Akses Admin Hapus Pesan" ON public.pesan_kontak
  FOR DELETE USING (true);

-- RLS Anggota
ALTER TABLE public.anggota ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Akses Publik Baca Anggota" ON public.anggota;
CREATE POLICY "Akses Publik Baca Anggota" ON public.anggota
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Akses Admin Kelola Anggota" ON public.anggota;
CREATE POLICY "Akses Admin Kelola Anggota" ON public.anggota
  FOR ALL USING (true);

-- =========================================================================
-- AKTIFKAN FITUR REALTIME (SINKRONISASI OTOMATIS KE SEMUA BROWSER / HP)
-- =========================================================================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'kegiatan'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.kegiatan;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'pesan_kontak'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.pesan_kontak;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'anggota'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.anggota;
  END IF;
END $$;

